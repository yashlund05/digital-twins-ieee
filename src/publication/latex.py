def generate_notation_tex(latex_dir: Path) -> str:
    """Generate formal mathematical notation glossary."""
    content = r"""% =============================================================================
% Mathematical Notation & Symbols
% =============================================================================

\section*{Nomenclature and Mathematical Notation}
\begin{description}
    \item[$y(t) \in \mathbb{R}^d$] Physical distribution feeder telemetry state vector at continuous timestep $t$.
    \item[$\hat{y}^{\text{DT}}(t) \in \mathbb{R}^d$] Digital Twin virtual state estimate computed via OpenDSS AC power flow.
    \item[$r(t) = y(t) - \hat{y}^{\text{DT}}(t)$] Physics-based residual vector.
    \item[$\Delta t \in \mathbb{R}_+$] Nominal Digital Twin telemetry synchronization latency interval (seconds).
    \item[$P_{\text{drop}} \in [0, 1)$] Stochastic Bernoulli packet transmission drop probability.
    \item[$\text{AoI}(t) = t - \tau(t)$] Realized Age of Information representing time elapsed since most recent telemetry arrival $\tau(t)$.
    \item[$F_1 \in [0, 1]$] Harmonic mean of anomaly detection precision and recall on the test partition.
    \item[$\text{MAPE} \in \mathbb{R}_+$] Mean Absolute Percentage Error of active power load estimation.
    \item[$\beta_{\text{AD}}, \beta_{\text{LE}}$] Normalized log-linear degradation slopes for anomaly detection and load estimation.
    \item[$\Delta\beta = \beta_{\text{AD}} - \beta_{\text{LE}}$] Degradation contrast testing research hypothesis $H_3$.
\end{description}
"""
    (latex_dir / "notation.tex").write_text(content, encoding="utf-8")
    return content


def generate_publication_results_tex(latex_dir: Path) -> str:
    """Generate publication narrative text summarizing empirical findings."""
    content = r"""% =============================================================================
% Empirical Results and Analysis Summary
% =============================================================================

\section{Experimental Evaluation and Findings}
Under continuous real-time synchronization ($\Delta t = 0$\,s, $P_{\text{drop}} = 0\%$), the physics-based residual representation $r(t)$ achieved an $F_1$-score of $0.9780$ using an LSTM Autoencoder, significantly outperforming raw telemetry ($F_1 = 0.5386$) due to effective background load cancellation.

However, as synchronization staleness increased, zero-order hold state divergence induced rapid degradation. At $\Delta t \ge 5$\,s, hold-last-state drift surpassed nominal reconstruction thresholds, collapsing residual $F_1$ to $0.1085$ and inverting the representation advantage in favor of raw telemetry ($F_1 = 0.5386$), which remained immune to virtual model divergence.

Formal hypothesis testing of $H_3$ ($\beta_{\text{AD}} > \beta_{\text{LE}}$) yielded $\Delta\beta = -1.2236$ ($95\%\, \text{CI}: [-1.3463, -1.1134]$, one-sided $p = 1.0000$), refuting $H_3$ with $100\%$ sign consistency across five independent random seeds. Rather than indicating superior resilience, this outcome demonstrates that anomaly detection collapses into an empirical noise floor within $\Delta t \le 5$\,s, whereas load estimation errors scale continuously and monotonically across several orders of magnitude.
"""
    (latex_dir / "publication_results.tex").write_text(content, encoding="utf-8")
    return content


def generate_master_phase12_tex(latex_dir: Path) -> str:
    """Generate standalone master LaTeX document wrapper."""
    content = r"""\documentclass[journal]{IEEEtran}
\usepackage{amsmath,amsfonts,amssymb}
\usepackage{graphicx}
\usepackage{booktabs}
\usepackage{multirow}
\usepackage{cite}

\title{Quantifying the Effect of Digital Twin Synchronization Staleness on Joint Short-Term Load Estimation and Unsupervised Anomaly Detection in a Distribution-Feeder Digital Twin}

\author{Research Team}

\begin{document}

\maketitle

\input{latex/notation.tex}

\input{latex/publication_results.tex}

\input{latex/tables.tex}

\input{latex/figures.tex}

\end{document}
"""
    (latex_dir / "phase12_artifacts.tex").write_text(content, encoding="utf-8")
    return content


def build_all_latex(output_dir: Path) -> dict[str, str]:
    """Orchestrate generation of all LaTeX publication deliverables."""
    lat_dir = output_dir / "latex"
    lat_dir.mkdir(parents=True, exist_ok=True)

    f_tex = generate_figures_tex(lat_dir)
    t_tex = generate_tables_tex(lat_dir)
    n_tex = generate_notation_tex(lat_dir)
    r_tex = generate_publication_results_tex(lat_dir)
    m_tex = generate_master_phase12_tex(lat_dir)

    logger.info("All LaTeX fragments and master document successfully generated.")
    return {
        "figures.tex": f_tex,
        "tables.tex": t_tex,
        "notation.tex": n_tex,
        "publication_results.tex": r_tex,
        "phase12_artifacts.tex": m_tex,
    }
